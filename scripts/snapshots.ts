// Writes the snapshot file the snapshot test compares against. Check the change on the
// preview page first, then: bun scripts/snapshots.ts > hooks/snapshots.data.ts
declare const console: { log: (text: string) => void }
import { shots, shotText } from '../hooks/snapshot'
import { setLanguage } from '../hooks/i18n'

// The expectations below are written in Korean.
setLanguage('ko')

const entries = shots().map(s => `  ${JSON.stringify(s.key)}: ${JSON.stringify(shotText(s))},`)
console.log(`// Generated by scripts/snapshots.ts; do not edit by hand.\nexport const SNAPSHOTS: Record<string, string> = {\n${entries.join('\n')}\n}`)
